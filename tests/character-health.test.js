function runCharacterHealthTests(api){
  let checks=0;const check=(ok,message)=>{checks++;if(!ok)throw Error(message);};
  const create=()=>api.create({random:()=>.5});
  const model=create();
  check(model.status().health===100&&model.status().wounds===0,'healthy start');
  check(!model.start('bandage','chest')&&model.items.bandages===6,'healthy parts consume no material');
  model.injure('leftLeg','cut');
  check(model.status().bleeding>0&&model.status().movement<1,'leg wound bleeds and slows movement');
  check(model.start('clean','leftLeg'),'disinfection can start');
  model.update(2.9);check(model.items.antiseptic===3&&model.action,'treatment does not consume supplies early');
  model.update(.1);check(model.items.antiseptic===2&&!model.action,'supply consumed once on completion');
  check(model.parts.leftLeg.wound.cleanTime>0,'completed disinfection protects the wound');
  check(!model.start('clean','leftLeg'),'already clean wound cannot waste antiseptic');
  check(model.start('bandage','leftLeg'),'clean wound can be bandaged');
  const injuredHealth=model.status().health;model.update(4);
  check(model.items.bandages===5&&model.status().bleeding===0,'clean bandage controls bleeding');
  check(model.status().health<100&&model.parts.leftLeg.wound,'bandaging does not instantly heal');
  check(!model.start('bandage','leftLeg'),'bandages cannot be stacked');
  const healthAfter=model.status().health;model.update(30);
  check(model.status().health>healthAfter&&model.status().health>=injuredHealth-1,'recovery is gradual');
  model.update(235);
  check(model.parts.leftLeg.wound.bandage.dirty,'bandages become dirty over time');
  check(model.parts.leftLeg.wound.infected,'neglected dirty dressing can cause local infection');
  check(!model.start('clean','leftLeg'),'dressing must be removed before cleaning');
  check(model.start('remove','leftLeg'),'old dressing can be removed');model.update(2);
  check(!model.parts.leftLeg.wound.bandage,'dressing is removed');
  check(model.start('clean','leftLeg'),'infected wound can be cleaned');model.update(3);
  check(!model.parts.leftLeg.wound.infected&&model.parts.leftLeg.wound.contamination===0,'infection treatment clears contamination');
  const cancel=create();cancel.injure('leftArm','cut');cancel.start('bandage','leftArm');cancel.update(2);
  cancel.update(.1,{moving:true});
  check(!cancel.action&&cancel.items.bandages===6,'movement cancels treatment without spending material');
  check(!cancel.start('bandage','leftArm',{moving:true}),'treatment cannot start while moving');
  cancel.start('bandage','leftArm');cancel.cancel();check(cancel.items.bandages===6,'manual cancellation is free');
  const broken=create();broken.injure('rightLeg','fracture');const before=broken.status().movement;
  check(!broken.start('bandage','rightLeg'),'fracture cannot be cured with a bandage');
  check(broken.start('splint','rightLeg'),'fracture accepts a splint');broken.update(7);
  check(broken.items.splints===0&&broken.parts.rightLeg.wound.splint,'splint consumed on completion');
  check(broken.status().movement>before,'immobilization reduces the movement penalty');
  const healthBeforePill=broken.status().health,painBeforePill=broken.status().pain;
  check(broken.start('painkiller','rightLeg'),'painkiller can be used for pain');broken.update(2);
  check(broken.status().pain<painBeforePill&&broken.status().health<healthBeforePill+1,'painkiller relieves pain without restoring health');
  check(!broken.start('painkiller','rightLeg'),'painkillers cannot be stacked during their effect');
  broken.update(65);check(broken.status().pain>0,'pain returns when medicine wears off');
  const empty=create();empty.injure('head','scratch');empty.items.bandages=1;
  empty.start('bandage','head');check(!empty.start('bandage','head'),'only one treatment at a time');empty.update(4);
  check(empty.items.bandages===0,'last bandage is consumed exactly once');
  empty.start('remove','head');empty.update(2);
  check(!empty.start('bandage','head')&&empty.items.bandages===0,'materials cannot go negative');
  const collapse=create();api.PARTS.forEach(([id])=>collapse.injure(id,'deep',2));
  check(collapse.status().critical,'severe untreated damage becomes critical');collapse.stabilize();
  check(!collapse.status().critical&&collapse.status().health<100&&collapse.status().wounds===7,'emergency recovery stabilizes without erasing wounds');
  const shortage=create();shortage.injure('chest','cut');shortage.start('bandage','chest');shortage.update(4);
  const remaining=shortage.parts.chest.wound.remaining;shortage.update(20,{hunger:0,thirst:0});
  check(remaining-shortage.parts.chest.wound.remaining<.1,'hunger and thirst slow healing');
  const atRate=hz=>{const h=create();h.injure('leftArm','cut');h.start('bandage','leftArm');for(let i=0;i<hz*10;i++)h.update(1/hz);return h;};
  const at30=atRate(30),at144=atRate(144);
  check(Math.abs(at30.status().health-at144.status().health)<.02&&Math.abs(at30.status().blood-at144.status().blood)<.02,'healing and bleeding are stable across frame rates');
  check(at30.items.bandages===at144.items.bandages,'frame rate does not change supply consumption');
  const stock=create();stock.restock();check(stock.items.bandages===9&&stock.items.antiseptic===5,'medical loot replenishes care materials');
  return checks+' character-health checks passed';
}
if(typeof module!=='undefined'&&module.exports)console.log(runCharacterHealthTests(require('../character-health.js')));
