// Run with: node tests/occlusion.test.js
const fs=require('node:fs'),path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../src/game.js'),'utf8');
const helpers=source.slice(source.indexOf('  const buildingOpacities='),source.indexOf('  function drawIsoDepthObjects('));
const api=new Function(helpers+';return {overlap:screenPolygonOverlapsRect,occludes:buildingOccludesActor,opacity:buildingOpacity};')();
const shape={base:[{x:100,y:150},{x:200,y:150},{x:200,y:180},{x:100,y:180}],roof:[{x:100,y:50},{x:200,y:50},{x:200,y:80},{x:100,y:80}]};
const body={left:145,right:155,top:100,bottom:120};
let checks=0;const check=(ok,message)=>{checks++;if(!ok)throw Error(message);};
check(api.occludes(shape,body,200,100),'a foreground wall covering the torso is detected');
check(api.occludes(shape,{...body,top:60,bottom:70},200,100),'a roof covering the head is detected');
check(api.occludes(shape,{...body,left:195,right:205},200,100),'partial overlap at a building edge is detected');
check(!api.occludes(shape,body,90,100),'a building behind the character stays opaque');
check(!api.occludes(shape,body,100,100),'equal depth draws the character after the building');
check(!api.occludes(shape,{...body,left:240,right:255},200,100),'nearby buildings without screen overlap stay opaque');
check(!api.occludes(shape,{...body,top:5,bottom:25},200,100),'a character above the roof silhouette does not fade it');
check(api.overlap([{x:0,y:9},{x:30,y:9},{x:30,y:11},{x:0,y:11}],{left:10,right:20,top:0,bottom:20}),'crossing edges count even when no polygon vertex is inside the body');
const diamond=[{x:0,y:10},{x:10,y:0},{x:20,y:10},{x:10,y:20}];
check(!api.overlap(diamond,{left:0,right:2,top:0,bottom:2}),'empty corners of a diamond bounding box do not trigger transparency');
const first=api.opacity(0,true,0);check(first<1&&first>.22,'transparency begins gradually');
let faded;for(let tick=1;tick<=60;tick++)faded=api.opacity(0,true,tick/60);
check(faded===.22,'an obstructing building settles at twenty-two percent opacity');
const initialRecovery=api.opacity(0,false,61/60);check(initialRecovery>.22&&initialRecovery<1,'opacity recovers gradually when the character emerges');
let restored;for(let tick=62;tick<=125;tick++)restored=api.opacity(0,false,tick/60);
check(restored===1,'the building returns fully opaque');
check(api.opacity(1,false,0)===1,'another building has independent opacity');
const drawSource=source.slice(source.indexOf('  function drawIsoBuilding('),source.indexOf('  function drawIsoTower('));
const alphas=[],stack=[];
const ctx=new Proxy({globalAlpha:.7,save(){stack.push(this.globalAlpha);},restore(){this.globalAlpha=stack.pop();},fillRect(){alphas.push(this.globalAlpha);},fill(){alphas.push(this.globalAlpha);}}, {get:(target,key)=>target[key]??(()=>{})});
const draw=new Function('ctx','polygon','drawUrbanBuildingSprite',drawSource+';return drawIsoBuilding;')(ctx,()=>alphas.push(ctx.globalAlpha),()=>alphas.push(ctx.globalAlpha));
draw(0,0,50,50,1,0,{...shape,w:82.5,h:82.5,lift:100},.22);
check(alphas.every(alpha=>alpha<=.7*.22+1e-8),'all building details and smoke respect the fade');
check(ctx.globalAlpha===.7&&stack.length===0,'building drawing restores the previous canvas opacity');
const stops=[],passes=[],blits=[],saved=[];let allocations=0;
const painter=new Proxy({createRadialGradient(){return {addColorStop(at,color){stops.push({at,alpha:Number(color.slice(color.lastIndexOf(',')+1,-1))});}};}},{get:(target,key)=>target[key]??(()=>{}),set:(target,key,value)=>(target[key]=value,true)});
const layer={width:0,height:0,getContext:()=>painter};
const document={createElement(){allocations++;return layer;}};
const revealContext={canvas:{},globalAlpha:.7,globalCompositeOperation:'source-over',filter:'none',
  getTransform:()=>({a:2,b:0,c:0,d:2,e:10,f:20}),setTransform(){},
  save(){saved.push(this.globalAlpha);},restore(){this.globalAlpha=saved.pop();},drawImage(...args){blits.push(args);}};
const reveal=new Function('ctx','W','H','document',helpers+';return drawBuildingWithReveal;')(revealContext,640,360,document);
reveal(alpha=>passes.push(alpha),.22,{x:320,y:172,radius:24});
check(passes.join(',')==='1','the building itself is rendered fully opaque once');
check(stops.length===5&&Math.abs(stops[0].alpha-.78)<1e-8&&stops[4].alpha===0,'the mask fades from a visible center to a fully solid building at the circle edge');
check(stops.every((stop,i)=>!i||stop.alpha<stops[i-1].alpha),'the circular edge has gradual intermediate transparency');
check(layer.width<120&&layer.height<120,'only a small patch is captured at high pixel density');
check(saved.length===0&&revealContext.globalAlpha===.7,'blending restores the caller canvas state');
reveal(()=>{},.22,{x:320,y:172,radius:24});
check(allocations===1,'the small reveal canvas is reused across frames');
passes.length=0;const blitsBefore=blits.length;
reveal(alpha=>passes.push(alpha),1,{x:320,y:172,radius:24});
check(passes.join(',')==='1'&&blits.length===blitsBefore,'unobstructed buildings avoid mask work');
console.log(checks+' occlusion checks passed');
