const assert=require('node:assert/strict');
const healthAPI=require('../src/character-health.js');
const ecologyAPI=require('../src/moss-creatures.js');
const health=healthAPI.create();
assert.equal(health.quickBandage(),false);
assert.equal(health.items.bandages,6);
health.injure('leftArm','cut',1);
health.injure('rightArm','deep',1);
const bleeding=health.status().bleeding;
assert.equal(health.quickBandage(),true);
assert.equal(health.items.bandages,5);
assert.ok(health.parts.rightArm.wound.bandage);
assert.ok(health.status().bleeding<bleeding);
health.update(.1,{moving:true});
assert.ok(health.parts.rightArm.wound.bandage,'emergency dressing remains while moving');
const ecology=ecologyAPI.createEcology({random:()=>.5,getBuildings:()=>[[100,100,40,40]],getSize:()=>({w:1200,h:1200}),isBlocked:()=>false,getShadows:()=>[]});
const light={daylight:0},target={x:600,y:600};
ecology.reset(light,target);
const creature=ecology.entities[0];Object.assign(creature,{x:610,y:600,indoors:false});
ecology.update(.1,{light,target,repellents:[{x:600,y:600,radius:150,room:-1}]});
assert.ok(creature.x>610,'creature flees the flare');
assert.equal(creature.behavior,'flee');
assert.equal(creature.pursuingPlayer,false);
console.log('Night survival checks passed');
